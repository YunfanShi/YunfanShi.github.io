import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.JACKYUN_PLAYWRIGHT_PATH || 'playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const base = process.env.JACKYUN_TEST_URL || 'http://127.0.0.1:3100';
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/resources');
  await page.evaluate(() => {
    const opaque = document.createElement('iframe'); opaque.id = 'opaque-adapter'; opaque.sandbox = 'allow-scripts';
    opaque.srcdoc = `<script>parent.postMessage({source:'supabase-adapter',type:'request-init',requestId:'opaque-probe'},'*')<\/script>`;
    document.body.appendChild(opaque);
    const trusted = document.createElement('iframe'); trusted.id = 'trusted-adapter';
    trusted.srcdoc = `<body>waiting<script>addEventListener('message',e=>{if(e.data?.type==='ready-ack')document.body.textContent='acknowledged'});parent.postMessage({source:'supabase-adapter',type:'request-init',requestId:'trusted-probe'},parent.location.origin)<\/script>`;
    document.body.appendChild(trusted);
  });
  await page.frameLocator('#trusted-adapter').getByText('acknowledged', { exact: true }).waitFor();
  assert.deepEqual(errors, [], 'opaque frames must be ignored; trusted handshake must work');
  await page.evaluate(() => { document.getElementById('opaque-adapter')?.remove(); document.getElementById('trusted-adapter')?.remove(); });
  console.log('PASS opaque-origin rejection and trusted legacy handshake');
  await page.goto(base + '/settings?section=pages');
  await page.getByRole('combobox', { name: '选择页面' }).waitFor();
  await page.getByRole('combobox', { name: /阅读字号/ }).selectOption('large');
  await page.getByRole('button', { name: '保存设置', exact: true }).first().click();
  await page.getByText('已保存到本机；登录后自动同步', { exact: true }).waitFor();
  await page.getByRole('combobox', { name: '选择页面' }).selectOption('schedule');
  assert.equal(await page.getByRole('combobox', { name: /阅读字号/ }).inputValue(), 'normal');
  await page.getByRole('checkbox', { name: /页面动态效果/ }).uncheck();
  await page.getByRole('button', { name: '保存设置', exact: true }).first().click();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('jackyun_settings_page_preferences')));
  assert.equal(saved['dashboard:size'], 'large'); assert.equal(saved['schedule:motion'], false);
  const pending = await page.evaluate(() => JSON.parse(JSON.parse(localStorage.getItem('jackyun_settings_pending_v1')).guest.page_preferences));
  assert.ok(pending.fields.includes('dashboard:size')); assert.ok(pending.fields.includes('schedule:motion'));
  await page.reload();
  await page.waitForFunction(() => Array.from(document.querySelectorAll('label')).find(label => label.textContent.includes('阅读字号'))?.querySelector('select')?.value === 'large');
  assert.equal(await page.getByRole('combobox', { name: /阅读字号/ }).inputValue(), 'large');
  await mkdir('../docs/screenshots', { recursive: true });
  await page.screenshot({ animations: 'disabled', path: '../docs/screenshots/workspace-3.5-pages-mobile.png' });
  await page.getByRole('combobox', { name: '设置分类' }).selectOption('ai');
  const provider = page.getByRole('combobox').filter({ has: page.locator('option[value="browser"]') });
  await provider.selectOption('browser');
  assert.equal(await page.getByRole('checkbox', { name: /Companion 全自动处理/ }).isDisabled(), true);
  await page.goto(base + '/dashboard');
  await page.waitForFunction(() => document.querySelector('[data-portal-main]')?.dataset.pageSize === 'large');
  await page.evaluate(() => localStorage.setItem('jackyun_settings_page_preferences', JSON.stringify({ intentPrefetch: false })));
  await page.route('**/settings?*', async route => { await new Promise(resolve => setTimeout(resolve, 3000)); await route.continue(); });
  await page.locator('.portal-mobile-nav').getByRole('link', { name: '设置', exact: true }).click();
  await page.getByText('正在打开页面…', { exact: true }).waitFor({ timeout: 1500 });
  await page.waitForURL('**/settings', { timeout: 20000 });
  await page.unroute('**/settings?*');
  console.log('PASS page isolation, durable drafts, manual AI, sensitive BETA gate, delayed navigation feedback');
  assert.deepEqual(errors, []);
  await context.close();

  const offline = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const app = await offline.newPage();
  await app.goto(base + '/schedule');
  await app.getByRole('button', { name: '暂时跳过', exact: true }).click();
  await app.evaluate(() => navigator.serviceWorker.ready);
  await app.reload();
  await app.waitForFunction(async () => {
    for (const key of await caches.keys()) if (key.includes('-pages-')) {
      if ((await (await caches.open(key)).keys()).some(request => new URL(request.url).pathname === '/schedule')) return true;
    }
    return false;
  }, { timeout: 20000 });
  await offline.setOffline(true);
  await app.goto(base + '/schedule', { waitUntil: 'domcontentloaded' });
  await app.locator('[data-portal-main]').waitFor();
  assert.equal(await app.getByRole('heading', { name: '当前处于离线状态' }).count(), 0);
  await app.goto(base + '/activity', { waitUntil: 'domcontentloaded' });
  await app.getByRole('heading', { name: '当前处于离线状态' }).waitFor();
  await offline.setOffline(false);
  await app.goto(base + '/schedule');
  await app.locator('[data-portal-main]').waitFor();
  await app.locator('nav[aria-label="日程视图"]').getByRole('button', { name: '学习', exact: true }).click();
  await app.locator('[data-cue-shop-open]').click();
  const shop = app.getByRole('dialog', { name: '星空商店' });
  await shop.waitFor();
  assert.equal(Math.round((await shop.boundingBox()).width), 390);
  await shop.getByRole('button', { name: '积分兑换', exact: true }).click();
  await shop.getByText('启航积分包', { exact: true }).waitFor();
  assert.ok((await shop.getByText('站内星空积分', { exact: true }).boundingBox()).y < 180);
  assert.ok((await shop.getByText('启航积分包', { exact: true }).boundingBox()).y < 760);
  await app.screenshot({ animations: 'disabled', path: '../docs/screenshots/workspace-3.5-shop-mobile.png' });
  await shop.getByRole('button', { name: '返回学习' }).click();
  console.log('PASS mobile CUE store and credit packs');
  console.log('PASS cached schedule offline, uncached exact-page fallback, online recovery');
  await offline.close();
} finally { await browser.close(); }
